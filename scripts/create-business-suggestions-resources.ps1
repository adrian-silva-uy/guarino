# 3) Reemplazar/crear FallbackAIService.cs para usar recursos
$FallbackPath = Join-Path $ServicesDir "FallbackAIService.cs"
$FallbackContent = @'
using System;
using System.Linq;
using System.Collections.Generic;
using System.Threading.Tasks;
using System.Globalization;
using GuarinoApp.Application.Common.Dtos;
using GuarinoApp.Application.Common.Interfaces;
using GuarinoApp.Infrastructure.Resources;
using Microsoft.Extensions.Logging;

namespace GuarinoApp.Infrastructure.Services
{
    /// <summary>
    /// Servicio de fallback para IA. Genera sugerencias basadas 100% en datos
    /// y delega a Ollama cuando está disponible.
    /// Usa los DTOs definidos en la capa Application (no define tipos duplicados).
    /// </summary>
    public class FallbackAIService : IAIService
    {
        private readonly OllamaAIService _ollamaService;
        private readonly ILogger<FallbackAIService> _logger;
        private readonly IDashboardDataService _dashboardService;

        public FallbackAIService(OllamaAIService ollamaService, ILogger<FallbackAIService> logger, IDashboardDataService dashboardService)
        {
            _ollamaService = ollamaService;
            _logger = logger;
            _dashboardService = dashboardService;
        }

        public bool IsAvailable => _ollamaService.IsAvailable;

        public async Task<string> ChatAsync(string prompt, List<ChatMessage> history)
        {
            try
            {
                if (_ollamaService.IsAvailable)
                {
                    var response = await _ollamaService.ChatAsync(prompt, history);
                    if (!string.IsNullOrEmpty(response))
                        return response;
                }
            }
            catch (Exception ex)
            {
                _logger.LogWarning(ex, "Ollama falló, usando fallback.");
            }

            var request = new BusinessSuggestionRequest
            {
                TotalStock = await _dashboardService.GetTotalStockAsync(DateTime.Now),
                StockByVariety = await _dashboardService.GetStockByVarietyAsync(DateTime.Now),
                PalletsWithoutClient = await _dashboardService.GetPalletsWithoutClientAsync(DateTime.Now),
                GrowthPercent = await _dashboardService.GetProjectedGrowthAsync(DateTime.Now),
                PeriodLabel = $""Actualizado: {DateTime.Now:dd/MM/yyyy}""
            };

            var suggestions = await GetBusinessSuggestionsAsync(request, history);
            if (suggestions != null && suggestions.Any())
                return string.Join("\n", suggestions.Select(s => s.Text));

            return "No pude generar una respuesta en este momento.";
        }

        /// <summary>
        /// Genera sugerencias basadas en datos (fallback determinista).
        /// Implementación con tipos totalmente cualificados para asegurar
        /// coincidencia exacta con la interfaz IAIService.
        /// </summary>
        public async Task<System.Collections.Generic.List<GuarinoApp.Application.Common.Dtos.BusinessSuggestionDto>>
            GetBusinessSuggestionsAsync(GuarinoApp.Application.Common.Dtos.BusinessSuggestionRequest request,
                                        System.Collections.Generic.List<GuarinoApp.Application.Common.Interfaces.ChatMessage>? history = null)
        {
            try
            {
                var result = new System.Collections.Generic.List<GuarinoApp.Application.Common.Dtos.BusinessSuggestionDto>();

                // Determinar topVar cuidadosamente (manejo de nullables)
                KeyValuePair<string,int>? topVarNullable = null;
                if (request.StockByVariety != null && request.StockByVariety.Any())
                {
                    topVarNullable = request.StockByVariety.OrderByDescending(kv => kv.Value).FirstOrDefault();
                }

                var hasTopVar = topVarNullable.HasValue;
                var topVarKey = hasTopVar ? topVarNullable.Value.Key : null;
                var topVarValue = hasTopVar ? topVarNullable.Value.Value : 0;

                // 1) Operaciones: pallets sin cliente
                if (request.PalletsWithoutClient > 0)
                {
                    result.Add(new GuarinoApp.Application.Common.Dtos.BusinessSuggestionDto
                    {
                        Text = string.Format(CultureInfo.CurrentCulture, BusinessSuggestions.AssignPallets_Text, request.PalletsWithoutClient),
                        Color = BusinessSuggestions.AssignPallets_Color,
                        Icon = BusinessSuggestions.AssignPallets_Icon
                    });
                }
                // 1b) Concentración por variedad
                else if (hasTopVar && topVarValue > Math.Max(100, request.TotalStock / 4))
                {
                    result.Add(new GuarinoApp.Application.Common.Dtos.BusinessSuggestionDto
                    {
                        Text = string.Format(CultureInfo.CurrentCulture, BusinessSuggestions.Concentration_Text, topVarKey ?? string.Empty, topVarValue),
                        Color = BusinessSuggestions.Concentration_Color,
                        Icon = BusinessSuggestions.Concentration_Icon
                    });
                }

                // 2) Planificación según crecimiento proyectado
                if (request.GrowthPercent > 3m)
                {
                    var extra = (int)Math.Ceiling(request.TotalStock * 0.05);
                    result.Add(new GuarinoApp.Application.Common.Dtos.BusinessSuggestionDto
                    {
                        Text = string.Format(CultureInfo.CurrentCulture, BusinessSuggestions.Planning_Growth_Text, request.GrowthPercent, extra),
                        Color = BusinessSuggestions.Planning_Growth_Color,
                        Icon = BusinessSuggestions.Planning_Growth_Icon
                    });
                }
                else
                {
                    result.Add(new GuarinoApp.Application.Common.Dtos.BusinessSuggestionDto
                    {
                        Text = string.Format(CultureInfo.CurrentCulture, BusinessSuggestions.Planning_Default_Text, request.GrowthPercent),
                        Color = BusinessSuggestions.Planning_Default_Color,
                        Icon = BusinessSuggestions.Planning_Default_Icon
                    });
                }

                // 3) Comercial/logística para top variedades
                if (request.StockByVariety != null && request.StockByVariety.Count > 0)
                {
                    var tops = request.StockByVariety.OrderByDescending(kv => kv.Value).Take(2);
                    var nombres = string.Join(", ", tops.Select(t => $""{t.Key} ({t.Value:N0} bins)""));
                    result.Add(new GuarinoApp.Application.Common.Dtos.BusinessSuggestionDto
                    {
                        Text = string.Format(CultureInfo.CurrentCulture, BusinessSuggestions.Commercial_Logistica_Text, nombres),
                        Color = BusinessSuggestions.Commercial_Logistica_Color,
                        Icon = BusinessSuggestions.Commercial_Logistica_Icon
                    });
                }

                if (!result.Any())
                {
                    result.Add(new GuarinoApp.Application.Common.Dtos.BusinessSuggestionDto
                    {
                        Text = BusinessSuggestions.Default_NoActions_Text,
                        Color = BusinessSuggestions.Default_NoActions_Color,
                        Icon = BusinessSuggestions.Default_NoActions_Icon
                    });
                }

                return result;
            }
            catch (Exception ex)
            {
                _logger.LogError(ex, "Error generando sugerencias fallback basadas en datos.");
                return new System.Collections.Generic.List<GuarinoApp.Application.Common.Dtos.BusinessSuggestionDto>
                {
                    new GuarinoApp.Application.Common.Dtos.BusinessSuggestionDto
                    {
                        Text = BusinessSuggestions.Default_NoActions_Text,
                        Color = BusinessSuggestions.Default_NoActions_Color,
                        Icon = BusinessSuggestions.Default_NoActions_Icon
                    }
                };
            }
        }
    }
}
'@
Set-Content -Path $FallbackPath -Value $FallbackContent -Encoding UTF8
Write-Host "Creado/actualizado: $FallbackPath"

# 4) Asegurar que el csproj incluya el EmbeddedResource para el .resx
if (Test-Path $CsprojPath) {
    Write-Host "Actualizando csproj: $CsprojPath"
    [xml]$csproj = Get-Content $CsprojPath -Raw

    $ns = $csproj.Project.GetType().Namespace
    $nsmgr = New-Object System.Xml.XmlNamespaceManager($csproj.NameTable)
    $nsmgr.AddNamespace("msb", $csproj.Project.GetType().Namespace)

    $found = $false
    foreach ($er in $csproj.Project.ItemGroup.EmbeddedResource) {
        if ($er.Include -eq "Resources\BusinessSuggestions.resx") { $found = $true; break }
    }

    if (-not $found) {
        # Crear ItemGroup si no existe
        $itemGroup = $csproj.CreateElement("ItemGroup", $ns)
        $embedded = $csproj.CreateElement("EmbeddedResource", $ns)
        $embedded.SetAttribute("Include", "Resources\BusinessSuggestions.resx")

        $generator = $csproj.CreateElement("Generator", $ns)
        $generator.InnerText = "PublicResXFileCodeGenerator"
        $embedded.AppendChild($generator) | Out-Null

        $last = $csproj.CreateElement("LastGenOutput", $ns)
        $last.InnerText = "BusinessSuggestions.Designer.cs"
        $embedded.AppendChild($last) | Out-Null

        $itemGroup.AppendChild($embedded) | Out-Null
        $csproj.Project.AppendChild($itemGroup) | Out-Null

        $csproj.Save($CsprojPath)
        Write-Host "Agregado EmbeddedResource al csproj."
    }
    else {
        Write-Host "El EmbeddedResource ya existe en el csproj."
    }
}
else {
    Write-Warning "No se encontró $CsprojPath. Añade manualmente la entrada al .csproj si es necesario."
}

if ($Build) {
    Write-Host "Ejecutando dotnet build..."
    dotnet build $RepoRoot
    if ($LASTEXITCODE -eq 0) {
        Write-Host "Build completado correctamente."
    } else {
        Write-Error "dotnet build falló. Revisa los errores."
    }
}

Write-Host "Script finalizado. Compila el proyecto para generar la clase fuertemente tipada si tu SDK lo requiere."
